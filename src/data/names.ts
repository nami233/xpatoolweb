// 帧头 ERR 是服务端唯一的失败信号（包体常常是空的），翻译成人话再带上码好排查
export function errorMessage(errorCode: number): string {
  const message = errorCodeMessage[errorCode]
  return message === undefined ? `未知错误（ERR=${errorCode}）` : `${message}（ERR=${errorCode}）`
}
