function linkSchemas(): void {
  for (const schema of Object.values(SCHEMAS)) {
    for (const field of Object.values(schema)) {
      if (field.type === 'message' && field.schemaName && !field.schema) {
        field.schema = SCHEMAS[field.schemaName]
      }
    }
  }
}

linkSchemas()

export function getSchema(name: string): MessageSchema | undefined {
  return SCHEMAS[name]
}
